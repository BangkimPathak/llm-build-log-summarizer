"""
CI Formatter Module
Translates ErrorAnalysisResult objects into publication-grade Markdown reports,
GitHub Actions Step Summaries ($GITHUB_STEP_SUMMARY), PR comments, and JSON payloads.
"""
from __future__ import annotations

import json
import os
from typing import Optional
from src.summarizer import ErrorAnalysisResult


class CIFormatter:
    """Formats diagnostic analysis for CI/CD pipeline display and reporting."""

    @staticmethod
    def to_markdown(result: ErrorAnalysisResult) -> str:
        """Generates comprehensive GitHub-flavored Markdown report."""
        badge_color = "red" if result.status == "FAILURE" else "green"
        file_loc = f"`{result.culprit_file}:{result.culprit_line}`" if result.culprit_file and result.culprit_line else (f"`{result.culprit_file}`" if result.culprit_file else "*System / Environment*")

        remediation_items = "\n".join([f"- [ ] {step}" for step in result.remediation_steps])

        diff_section = ""
        if result.suggested_diff_patch:
            if result.suggested_diff_patch.startswith("---"):
                diff_section = f"""### 🛠️ Suggested Code Fix Diff
```diff
{result.suggested_diff_patch}
```"""
            else:
                diff_section = f"""### 🛠️ Suggested Fix Command
```bash
{result.suggested_diff_patch}
```"""

        md = f"""## 🚨 Automated CI Build Failure Diagnostic Summary

> **Status:** `{result.status}` &nbsp;|&nbsp; **Ecosystem:** `{result.ecosystem}` &nbsp;|&nbsp; **Error Category:** `{result.error_category}` &nbsp;|&nbsp; **Confidence:** `{result.confidence_score * 100:.1f}%`

---

### 🔍 Root Cause Analysis
**Culprit Location:** {file_loc}  
**Diagnostic Summary:**
> {result.root_cause_explanation}

---

### 📋 Recommended Remediation Steps
{remediation_items}

---

{diff_section}

---

### 📊 Token Reduction & Performance Metrics
| Metric | Measurement | Description |
| :--- | :--- | :--- |
| **Raw Log Volume** | **{result.raw_lines:,} lines** ({result.raw_tokens:,} tokens) | Original CI console stdout/stderr log |
| **Distilled Error Slice** | **{result.cleaned_lines:,} lines** ({result.distilled_tokens:,} tokens) | Preprocessed & context-sliced error region |
| **Token Savings** | **{result.token_savings_pct}% reduction** | Saved LLM context bandwidth & API quota |
| **Diagnosis Latency** | **{result.analysis_latency_ms:.2f} ms** | Time taken by preprocessor + {result.provider_used} |
| **Diagnostic Engine** | `{result.provider_used}` | Inference engine utilized |

*Report generated by **LLM-Based Build/Error-Log Summarizer** • Student: **Bangkim Pathak (24BTRAO006)** • Jain University*
"""
        return md.strip()

    @classmethod
    def write_step_summary(cls, result: ErrorAnalysisResult, custom_path: Optional[str] = None) -> str:
        """
        Appends the markdown diagnostic summary directly to GitHub Actions $GITHUB_STEP_SUMMARY,
        or to a specified local file path.
        """
        summary_md = cls.to_markdown(result)
        target_path = custom_path or os.getenv("GITHUB_STEP_SUMMARY")

        if target_path:
            with open(target_path, "a", encoding="utf-8") as f:
                f.write(summary_md + "\n\n")
            return target_path
        return ""

    @classmethod
    def write_pr_comment(cls, result: ErrorAnalysisResult, output_file: str) -> None:
        """Writes the diagnostic summary to a file suitable for GitHub PR commenting actions."""
        comment_md = cls.to_markdown(result)
        with open(output_file, "w", encoding="utf-8") as f:
            f.write(comment_md)

    @classmethod
    def to_json(cls, result: ErrorAnalysisResult) -> str:
        """Serializes result into structured JSON string."""
        return json.dumps(result.to_dict(), indent=2)
